"""Alembic environment.

Migrations are hand-written (RLS, grants and triggers can't be autogenerated),
so there is no target metadata. The URL comes from, in order:
  1. ``config.attributes["url"]`` (tests pass the test database this way)
  2. the ``MIGRATIONS_DATABASE_URL`` environment variable (the migrator user)
"""

import os
from logging.config import fileConfig

from alembic import context
from sqlalchemy import create_engine, pool

config = context.config
if config.config_file_name is not None and not config.attributes.get("skip_logging"):
    fileConfig(config.config_file_name, disable_existing_loggers=False)


def _database_url() -> str:
    url = config.attributes.get("url") or os.environ.get("MIGRATIONS_DATABASE_URL")
    if not url:
        raise RuntimeError(
            "Set MIGRATIONS_DATABASE_URL to the migrator user's URL "
            "(backend-development-guide.md §3.6)."
        )
    return url


def run_migrations_offline() -> None:
    context.configure(url=_database_url(), literal_binds=True, target_metadata=None)
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    engine = create_engine(_database_url(), poolclass=pool.NullPool)
    with engine.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=None,
            transaction_per_migration=True,
        )
        with context.begin_transaction():
            context.run_migrations()
    engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
